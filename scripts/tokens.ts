// Turns src/ui/theme/tokens.json into src/ui/theme/tokens.ts.
//   npm run tokens            write the file
//   npm run tokens -- --check fail if the committed file is out of date (CI)
import fs from 'node:fs';
import path from 'node:path';

import { format, resolveConfig } from 'prettier';

export const TOKENS_JSON = 'src/ui/theme/tokens.json';
export const TOKENS_TS = 'src/ui/theme/tokens.ts';
export const COLOR_SETS_TS = 'src/domain/theme/colorSets.ts';

const root = path.resolve(__dirname, '..');

type Json = {
  color: { themes: { id: string }[]; tokens: { name: string; value: Record<string, string> }[] };
  type: {
    groups: {
      styles: {
        name: string;
        fontSize: string;
        lineHeight: string;
        fontWeight: number;
        letterSpacing?: string;
      }[];
    }[];
  };
  spacing: { tokens: { name: string; value: string }[] };
  radius: { tokens: { name: string; value: string }[] };
  size: { tokens: { name: string; value: string }[] };
  opacity: { tokens: { name: string; value: string }[] };
  shadow: { tokens: { name: string; value: Record<string, string> }[] };
};

const px = (v: string | undefined) => (v ? parseFloat(v) : 0);

/** '0 6px 16px rgba(31,42,46,0.22)' → offset, blur, color channels and opacity; 'none' → null. */
function parseShadow(value: string) {
  if (value === 'none') return null;
  const m =
    /^(-?\d+)(?:px)? (-?\d+)(?:px)? (\d+)(?:px)? rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)$/.exec(
      value,
    );
  if (!m) throw new Error(`Unreadable shadow: ${value}`);
  const [, x, y, blur, r, g, b, a] = m;
  return {
    offsetX: Number(x),
    offsetY: Number(y),
    blur: Number(blur),
    rgb: `${r} ${g} ${b}`,
    opacity: Number(a),
  };
}

const strip = (prefix: string, name: string) => name.replace(prefix, '');

export async function renderTokens(json: Json): Promise<Record<string, string>> {
  const setIds = json.color.themes.map((t) => t.id);
  const themeIds = [...new Set(setIds.map((id) => id.replace(/-(light|dark)$/, '')))];

  const colorSets = Object.fromEntries(
    setIds.map((id) => [
      id,
      Object.fromEntries(json.color.tokens.map((t) => [t.name, t.value[id]])),
    ]),
  );
  const typeStyles = Object.fromEntries(
    json.type.groups.flatMap((g) =>
      g.styles.map((s) => [
        s.name,
        {
          fontSize: px(s.fontSize),
          lineHeight: px(s.lineHeight),
          letterSpacing: px(s.letterSpacing),
          weight: s.fontWeight,
        },
      ]),
    ),
  );
  const scale = (tokens: { name: string; value: string }[], prefix: string) =>
    Object.fromEntries(tokens.map((t) => [strip(prefix, t.name), px(t.value)]));
  const shadows = Object.fromEntries(
    json.shadow.tokens.map((t) => [
      strip('shadow-', t.name),
      Object.fromEntries(setIds.map((id) => [id, parseShadow(t.value[id]!)])),
    ]),
  );

  const lit = (v: unknown) => JSON.stringify(v, null, 2);
  const header = `// GENERATED by scripts/tokens.ts from ${TOKENS_JSON}: do not edit. Run \`npm run tokens\`.`;

  // Color data is pure, so it lives in the domain, where resolvePalette needs it.
  const colorSource = `${header}

export const themeIds = ${lit(themeIds)} as const;
export type ThemeId = (typeof themeIds)[number];

export const colorSetIds = ${lit(setIds)} as const;
export type ColorSetId = (typeof colorSetIds)[number];

export type ColorToken = ${json.color.tokens.map((t) => `'${t.name}'`).join(' | ')};

export const colorSets: Readonly<Record<ColorSetId, Readonly<Record<ColorToken, string>>>> = ${lit(colorSets)};
`;

  const uiSource = `${header}

export {
  colorSetIds,
  colorSets,
  themeIds,
  type ColorSetId,
  type ColorToken,
  type ThemeId,
} from '@/domain/theme/colorSets';
import type { ColorSetId } from '@/domain/theme/colorSets';

export type TypeStyleName = ${Object.keys(typeStyles)
    .map((n) => `'${n}'`)
    .join(' | ')};

export const typeStyles: Readonly<Record<TypeStyleName, { fontSize: number; lineHeight: number; letterSpacing: number; weight: 400 | 600 | 700 | 800 }>> = ${lit(typeStyles)};

/** Pixels. */
export const spacing = ${lit(scale(json.spacing.tokens, 'space-'))} as const;
export const radius = ${lit(scale(json.radius.tokens, 'radius-'))} as const;
export const size = ${lit(scale(json.size.tokens, 'size-'))} as const;
export const opacity = ${lit(scale(json.opacity.tokens, 'opacity-'))} as const;

export type Shadow = { offsetX: number; offsetY: number; blur: number; rgb: string; opacity: number } | null;
export const shadows: Readonly<Record<${Object.keys(shadows)
    .map((n) => `'${n}'`)
    .join(' | ')}, Readonly<Record<ColorSetId, Shadow>>>> = ${lit(shadows)};
`;
  const pretty = async (source: string, file: string) =>
    format(source, {
      ...((await resolveConfig(path.join(root, file))) ?? {}),
      parser: 'typescript',
      plugins: [],
    });
  return {
    [TOKENS_TS]: await pretty(uiSource, TOKENS_TS),
    [COLOR_SETS_TS]: await pretty(colorSource, COLOR_SETS_TS),
  };
}

/** True when every generated file on disk matches what `json` produces. */
export async function checkTokens(json: Json, read: (file: string) => string): Promise<boolean> {
  const files = await renderTokens(json);
  return Object.entries(files).every(([file, content]) => read(file) === content);
}

const readFile = (file: string) => {
  const abs = path.join(root, file);
  return fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8') : '';
};

async function main() {
  const json = JSON.parse(readFile(TOKENS_JSON)) as Json;
  if (process.argv.includes('--check')) {
    if (!(await checkTokens(json, readFile))) {
      console.error(
        `Generated tokens are out of date with ${TOKENS_JSON}. Run \`npm run tokens\`.`,
      );
      process.exit(1);
    }
    console.log('Generated tokens are up to date.');
    return;
  }
  for (const [file, content] of Object.entries(await renderTokens(json))) {
    fs.writeFileSync(path.join(root, file), content);
    console.log(`Wrote ${file}.`);
  }
}

if (require.main === module) void main();
